# -*- coding: utf-8 -*-
from datetime import datetime, time, timedelta

from odoo import _, api, fields, models, tools
from odoo.exceptions import UserError
from odoo.tools.misc import format_date

# Default period used when the report is opened straight from the menu.
DEFAULT_PERIOD_DAYS = 365


class ImexInventoryReport(models.Model):
    """Inventory In/Out Summary.

    This used to be a PostgreSQL view (``_auto = False``) whose numeric columns
    were hard-coded to ``0.0`` and patched afterwards inside an override of
    ``read()``.  Because of that, export produced zeros and filtering, sorting
    and group-by on the quantities never worked.

    The model is now an ordinary stored model.  ``generate()`` computes the
    whole report in one SQL statement and materialises real rows (one set per
    user), so export, filters, sorting, group-by and list totals all behave
    normally.
    """

    _name = "imex.inventory.report"
    _description = "Inventory In/Out Summary"
    _order = "id"
    _rec_name = "product_id"

    user_id = fields.Many2one(
        "res.users",
        string="Generated By",
        index=True,
        required=True,
        ondelete="cascade",
        default=lambda self: self.env.user,
    )
    date_from = fields.Date(string="From", readonly=True)
    date_to = fields.Date(string="To", readonly=True)

    product_id = fields.Many2one("product.product", string="Product", index=True, readonly=True)
    product_uom = fields.Many2one("uom.uom", string="UoM", readonly=True)
    product_category = fields.Many2one("product.category", string="Category", index=True, readonly=True)
    location = fields.Many2one("stock.location", string="Location", index=True, readonly=True)

    standard_price = fields.Float("Unit Cost", digits="Product Price", readonly=True)
    initial = fields.Float("Opening", digits="Product Unit of Measure", readonly=True)
    product_in = fields.Float("In", digits="Product Unit of Measure", readonly=True)
    product_out = fields.Float("Out", digits="Product Unit of Measure", readonly=True)
    balance = fields.Float("Balance", digits="Product Unit of Measure", readonly=True)
    total_value = fields.Float("Total Value", digits="Product Price", readonly=True)

    # ------------------------------------------------------------------
    # Schema migration
    # ------------------------------------------------------------------

    def _auto_init(self):
        """Drop the legacy SQL view before the real table is created.

        Earlier versions of this module declared ``_auto = False`` and created
        a PostgreSQL VIEW named ``imex_inventory_report``.  Odoo would see that
        relation, assume the table exists and fail while adding columns.
        Removing the view first makes ``-u mj_inventory_report`` work without
        any manual SQL.
        """
        self.env.cr.execute(
            """
            SELECT c.relkind
              FROM pg_class c
              JOIN pg_namespace n ON n.oid = c.relnamespace
             WHERE c.relname = %s
               AND n.nspname = current_schema()
            """,
            (self._table,),
        )
        row = self.env.cr.fetchone()
        if row and row[0] == "v":
            tools.drop_view_if_exists(self.env.cr, self._table)
        return super()._auto_init()

    # ------------------------------------------------------------------
    # Report generation
    # ------------------------------------------------------------------

    @api.model
    def _default_period(self):
        today = fields.Date.context_today(self)
        return today - timedelta(days=DEFAULT_PERIOD_DAYS), today

    @api.model
    def generate(self, date_from=None, date_to=None, location_ids=None,
                 product_ids=None, category_ids=None):
        """(Re)build the report rows belonging to the current user.

        Everything is done in SQL so the report stays usable on databases with
        a large ``stock_move_line`` table.  Only ``standard_price`` needs a
        Python round-trip, because it is a company-dependent field.
        """
        default_from, default_to = self._default_period()
        date_from = fields.Date.to_date(date_from) or default_from
        date_to = fields.Date.to_date(date_to) or default_to

        if date_from > date_to:
            raise UserError(_("Date From cannot be after Date To."))

        # Half-open [dt_from, dt_to) window on the UTC move date.
        dt_from = datetime.combine(date_from, time.min)
        dt_to = datetime.combine(date_to + timedelta(days=1), time.min)

        uid = self.env.uid
        cr = self.env.cr

        cr.execute("DELETE FROM imex_inventory_report WHERE user_id = %s", (uid,))

        params = {
            "uid": uid,
            "date_from": date_from,
            "date_to": date_to,
            "dt_from": dt_from,
            "dt_to": dt_to,
            "company_ids": tuple(self.env.companies.ids) or (0,),
        }

        move_clauses = ""
        if location_ids:
            # child locations are rolled up into the selected one
            all_locations = self.env["stock.location"].search(
                [("id", "child_of", list(location_ids)), ("usage", "=", "internal")]
            )
            move_clauses += " AND l.location_id IN %(location_ids)s"
            params["location_ids"] = tuple(all_locations.ids) or (0,)
        if product_ids:
            move_clauses += " AND sml.product_id IN %(product_ids)s"
            params["product_ids"] = tuple(product_ids) or (0,)

        product_clauses = ""
        if category_ids:
            all_categories = self.env["product.category"].search(
                [("id", "child_of", list(category_ids))]
            )
            product_clauses += " AND pt.categ_id IN %(category_ids)s"
            params["category_ids"] = tuple(all_categories.ids) or (0,)

        query = """
            INSERT INTO imex_inventory_report (
                create_uid, create_date, write_uid, write_date, user_id,
                date_from, date_to,
                product_id, product_uom, product_category, location,
                standard_price, initial, product_in, product_out, balance,
                total_value
            )
            SELECT
                %(uid)s, (now() AT TIME ZONE 'UTC'), %(uid)s, (now() AT TIME ZONE 'UTC'), %(uid)s,
                %(date_from)s, %(date_to)s,
                agg.product_id,
                pt.uom_id,
                pt.categ_id,
                agg.location,
                0.0,
                agg.initial,
                agg.product_in,
                agg.product_out,
                agg.initial + agg.product_in - agg.product_out,
                0.0
            FROM (
                SELECT
                    sml.product_id AS product_id,
                    l.location_id AS location,
                    COALESCE(SUM(
                        CASE WHEN sm.date < %(dt_from)s
                             THEN l.sign * sml.quantity ELSE 0 END
                    ), 0) AS initial,
                    COALESCE(SUM(
                        CASE WHEN sm.date >= %(dt_from)s AND l.sign = 1
                             THEN sml.quantity ELSE 0 END
                    ), 0) AS product_in,
                    COALESCE(SUM(
                        CASE WHEN sm.date >= %(dt_from)s AND l.sign = -1
                             THEN sml.quantity ELSE 0 END
                    ), 0) AS product_out
                FROM stock_move_line sml
                JOIN stock_move sm
                    ON sm.id = sml.move_id
                -- one row per side of the move, so an internal transfer feeds
                -- both the destination (in) and the source (out)
                JOIN LATERAL (
                    VALUES (sml.location_dest_id, 1), (sml.location_id, -1)
                ) AS l(location_id, sign) ON TRUE
                JOIN stock_location sl
                    ON sl.id = l.location_id AND sl.usage = 'internal'
                WHERE sm.state = 'done'
                  AND sm.date < %(dt_to)s
                  AND sml.company_id IN %(company_ids)s
                  {move_clauses}
                GROUP BY sml.product_id, l.location_id
            ) agg
            JOIN product_product pp ON pp.id = agg.product_id
            JOIN product_template pt ON pt.id = pp.product_tmpl_id
            WHERE (agg.initial <> 0 OR agg.product_in <> 0 OR agg.product_out <> 0)
              {product_clauses}
            ORDER BY pt.categ_id, pp.default_code NULLS LAST, agg.product_id, agg.location
        """.format(move_clauses=move_clauses, product_clauses=product_clauses)

        cr.execute(query, params)

        self._fill_valuation(uid)
        self.invalidate_model()

        return True

    def _fill_valuation(self, uid):
        """Set ``standard_price`` / ``total_value`` on the freshly built rows.

        ``product.standard_price`` is company-dependent, so it is read through
        the ORM and pushed back with a single UPDATE.
        """
        cr = self.env.cr
        cr.execute(
            "SELECT DISTINCT product_id FROM imex_inventory_report WHERE user_id = %s",
            (uid,),
        )
        product_ids = [row[0] for row in cr.fetchall() if row[0]]
        if not product_ids:
            return

        products = self.env["product.product"].browse(product_ids).exists()
        prices = {p.id: p.standard_price or 0.0 for p in products}
        if not prices:
            return

        cr.execute(
            """
            UPDATE imex_inventory_report r
               SET standard_price = v.price,
                   total_value = r.balance * v.price
              FROM (
                    SELECT unnest(%s::int[]) AS product_id,
                           unnest(%s::numeric[]) AS price
                   ) v
             WHERE r.product_id = v.product_id
               AND r.user_id = %s
            """,
            (list(prices.keys()), list(prices.values()), uid),
        )

    # ------------------------------------------------------------------
    # Actions
    # ------------------------------------------------------------------

    @api.model
    def action_open_report(self, date_from=None, date_to=None, location_ids=None,
                           product_ids=None, category_ids=None):
        """Regenerate the report and open it.

        Bound to the menu through a server action, so the user gets fresh
        numbers without going through a wizard first.
        """
        self.generate(
            date_from=date_from,
            date_to=date_to,
            location_ids=location_ids,
            product_ids=product_ids,
            category_ids=category_ids,
        )

        context = dict(self.env.context)

        default_from, default_to = self._default_period()
        used_from = fields.Date.to_date(date_from) or default_from
        used_to = fields.Date.to_date(date_to) or default_to

        return {
            "type": "ir.actions.act_window",
            "name": _(
                "Inventory In/Out Summary  (%(start)s → %(end)s)",
                start=format_date(self.env, used_from),
                end=format_date(self.env, used_to),
            ),
            "res_model": "imex.inventory.report",
            "view_mode": "list,kanban,pivot",
            "views": [
                (self.env.ref("mj_inventory_report.view_imex_inventory_report_list").id, "list"),
                (self.env.ref("mj_inventory_report.view_imex_inventory_report_kanban").id, "kanban"),
                (self.env.ref("mj_inventory_report.view_imex_inventory_report_pivot").id, "pivot"),
            ],
            "search_view_id": [self.env.ref("mj_inventory_report.view_imex_inventory_report_search").id],
            "domain": [("user_id", "=", self.env.uid)],
            "context": context,
            "target": "current",
        }

    def action_change_period(self):
        """Re-open the wizard, prefilled with the period currently on screen.

        Bound to the "Change Period" button in the list view header, so the
        date range can be changed without going back to the menu.
        """
        row = self.env["imex.inventory.report"].search(
            [("user_id", "=", self.env.uid)], limit=1
        )
        default_from, default_to = self._default_period()

        context = dict(self.env.context)
        context.update(
            default_date_from=row.date_from or default_from,
            default_date_to=row.date_to or default_to,
        )

        return {
            "type": "ir.actions.act_window",
            "name": _("Select Date Range"),
            "res_model": "imex.inventory.wizard",
            "view_mode": "form",
            "view_id": self.env.ref("mj_inventory_report.view_imex_inventory_wizard").id,
            "target": "new",
            "context": context,
        }

    def action_open_product(self):
        self.ensure_one()
        return {
            "type": "ir.actions.act_window",
            "name": _("Product"),
            "res_model": "product.product",
            "view_mode": "form",
            "res_id": self.product_id.id,
            "target": "current",
        }

    def action_view_move_history(self):
        self.ensure_one()

        date_from = self.date_from or self.env.context.get("date_from")
        date_to = self.date_to or self.env.context.get("date_to")
        if not date_from or not date_to:
            raise UserError(_("This report line has no period. Please regenerate the report."))

        dt_from = datetime.combine(fields.Date.to_date(date_from), time.min)
        dt_to = datetime.combine(fields.Date.to_date(date_to) + timedelta(days=1), time.min)

        locations = self.env["stock.location"].search([("id", "child_of", self.location.id)])

        domain = [
            ("state", "=", "done"),
            ("product_id", "=", self.product_id.id),
            ("date", ">=", dt_from),
            ("date", "<", dt_to),
            "|",
            ("location_id", "in", locations.ids),
            ("location_dest_id", "in", locations.ids),
        ]

        return {
            "type": "ir.actions.act_window",
            "name": _("Stock Move History"),
            "res_model": "stock.move.line",
            "view_mode": "list,form",
            "domain": domain,
            "target": "current",
        }
